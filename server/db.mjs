/**
 * Database layer with two interchangeable backends:
 *   - PostgreSQL when DATABASE_URL is set (production: Render Postgres, Neon, Supabase, …).
 *     Accounts and their work live in the database, so you see the same data on every device.
 *   - SQLite (node:sqlite) otherwise, in DATA_DIR/stepwise.db (local development, zero setup).
 *
 * Every query is written once in SQL both understand ("?" placeholders, ON CONFLICT, RETURNING)
 * and goes through the same async API:
 *   one(sql, params) → first row | undefined
 *   all(sql, params) → rows
 *   run(sql, params) → { changes }
 *   tx(async (q) => …) → runs fn atomically; q has one/all/run bound to the transaction
 */
import { mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DRIVER = process.env.DATABASE_URL ? 'postgres' : 'sqlite';

// ------------------------------------------------------------------ schema
const SQLITE_SCHEMA = `
PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  email TEXT NOT NULL UNIQUE COLLATE NOCASE,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  prefs TEXT NOT NULL DEFAULT '{}',
  created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS submissions (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  problem_id TEXT NOT NULL,
  language TEXT NOT NULL,
  verdict TEXT NOT NULL,
  passed INTEGER NOT NULL,
  total INTEGER NOT NULL,
  runtime_ms INTEGER,
  code TEXT NOT NULL,
  created_at INTEGER NOT NULL
);
`;

const PG_SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  prefs TEXT NOT NULL DEFAULT '{}',
  created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  problem_id TEXT NOT NULL,
  language TEXT NOT NULL,
  verdict TEXT NOT NULL,
  passed INTEGER NOT NULL,
  total INTEGER NOT NULL,
  runtime_ms INTEGER,
  code TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
`;

/** Tables whose definition is identical in both databases (ID = user id type, TS = millisecond timestamp). */
const COMMON_SCHEMA = (ID, TS) => `
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at ${TS} NOT NULL
);
CREATE TABLE IF NOT EXISTS concept_progress (
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  concept_id TEXT NOT NULL,
  completed_at ${TS} NOT NULL,
  PRIMARY KEY (user_id, concept_id)
);
CREATE TABLE IF NOT EXISTS bookmarks (
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  concept_id TEXT NOT NULL,
  created_at ${TS} NOT NULL,
  PRIMARY KEY (user_id, concept_id)
);
CREATE TABLE IF NOT EXISTS problem_progress (
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  problem_id TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'todo',
  saved INTEGER NOT NULL DEFAULT 0,
  attempts INTEGER NOT NULL DEFAULT 0,
  solved_at ${TS},
  last_lang TEXT,
  PRIMARY KEY (user_id, problem_id)
);
CREATE INDEX IF NOT EXISTS idx_sub_user ON submissions(user_id, created_at DESC);
CREATE TABLE IF NOT EXISTS snippets (
  id TEXT NOT NULL,
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  language TEXT NOT NULL,
  code TEXT NOT NULL,
  stdin TEXT NOT NULL DEFAULT '',
  updated_at ${TS} NOT NULL,
  PRIMARY KEY (user_id, id)
);
CREATE TABLE IF NOT EXISTS test_attempts (
  id TEXT NOT NULL,
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  space TEXT NOT NULL,
  data TEXT NOT NULL,
  created_at ${TS} NOT NULL,
  PRIMARY KEY (user_id, id)
);
CREATE INDEX IF NOT EXISTS idx_attempt_user ON test_attempts(user_id, created_at DESC);
CREATE TABLE IF NOT EXISTS user_kv (
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ns TEXT NOT NULL,
  key TEXT NOT NULL,
  value TEXT NOT NULL,
  updated_at ${TS} NOT NULL,
  PRIMARY KEY (user_id, ns, key)
);
CREATE TABLE IF NOT EXISTS coding_tests (
  id TEXT NOT NULL,
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  level TEXT NOT NULL,
  data TEXT NOT NULL,
  created_at ${TS} NOT NULL,
  updated_at ${TS} NOT NULL,
  PRIMARY KEY (user_id, id)
);
CREATE INDEX IF NOT EXISTS idx_coding_user ON coding_tests(user_id, created_at DESC);
CREATE TABLE IF NOT EXISTS activity (
  user_id ${ID} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  count INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, day)
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);
`;

// ------------------------------------------------------------------ backends
let backend;

if (DRIVER === 'postgres') {
  const pg = (await import('pg')).default;
  // BIGINT (timestamps, ids, COUNT) and NUMERIC (SUM) arrive as strings by default; they all fit in a JS number here.
  pg.types.setTypeParser(20, (v) => Number(v));
  pg.types.setTypeParser(1700, (v) => Number(v));
  const url = process.env.DATABASE_URL;
  // SSL: off for localhost and private hostnames without a dot (Render's internal URL, e.g. dpg-xxxx-a);
  // on for public hosts (Render's external URL, Neon, Supabase …). PGSSL=require|disable overrides.
  let host = '';
  try {
    host = new URL(url).hostname;
  } catch {
    /* unusual connection string: let pg parse it */
  }
  const privateHost = !host || host === 'localhost' || host === '127.0.0.1' || !host.includes('.');
  const sslWanted = process.env.PGSSL ? process.env.PGSSL !== 'disable' : /sslmode=(require|verify)/.test(url) || !privateHost;
  const ssl = sslWanted ? { rejectUnauthorized: false } : false;
  const pool = new pg.Pool({ connectionString: url, ssl, max: Number(process.env.PG_POOL_MAX || 10), idleTimeoutMillis: 30000 });
  pool.on('error', (e) => console.error('Postgres pool error:', e.message));

  // "?" → $1, $2 … (our SQL never contains a literal question mark).
  const toPg = (sql) => {
    let i = 0;
    return sql.replace(/\?/g, () => `$${++i}`);
  };
  const make = (exec) => ({
    one: async (sql, params = []) => (await exec(toPg(sql), params)).rows[0],
    all: async (sql, params = []) => (await exec(toPg(sql), params)).rows,
    run: async (sql, params = []) => ({ changes: (await exec(toPg(sql), params)).rowCount }),
  });
  const base = make((text, values) => pool.query(text, values));
  backend = {
    ...base,
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const r = await fn(make((text, values) => client.query(text, values)));
        await client.query('COMMIT');
        return r;
      } catch (e) {
        await client.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        client.release();
      }
    },
    async init() {
      await pool.query(PG_SCHEMA + COMMON_SCHEMA('BIGINT', 'BIGINT'));
    },
    close: () => pool.end(),
    describe: () => `postgres (${url.replace(/\/\/[^@]*@/, '//***@').replace(/\?.*$/, '')})`,
  };
} else {
  const { DatabaseSync } = await import('node:sqlite');
  const dataDir = process.env.DATA_DIR || join(root, 'data');
  mkdirSync(dataDir, { recursive: true });
  const file = join(dataDir, 'stepwise.db');
  if (process.env.NODE_ENV === 'production')
    console.warn(
      '\n⚠  DATABASE_URL is not set: accounts are stored in a local SQLite file.\n' +
        '   On hosts with temporary disks (Render, Railway, Heroku) this data is LOST on every deploy or restart.\n' +
        '   Set DATABASE_URL to a PostgreSQL database so users keep their work on every device.\n'
    );
  const sqlite = new DatabaseSync(file);
  const cache = new Map();
  const stmt = (sql) => {
    let s = cache.get(sql);
    if (!s) cache.set(sql, (s = sqlite.prepare(sql)));
    return s;
  };
  const q = {
    one: async (sql, params = []) => stmt(sql).get(...params),
    all: async (sql, params = []) => stmt(sql).all(...params),
    run: async (sql, params = []) => ({ changes: Number(stmt(sql).run(...params).changes) }),
  };
  // node:sqlite is synchronous and single-connection: transactions are serialised with a queue.
  let chain = Promise.resolve();
  backend = {
    ...q,
    tx(fn) {
      const run = chain.then(async () => {
        sqlite.exec('BEGIN');
        try {
          const r = await fn(q);
          sqlite.exec('COMMIT');
          return r;
        } catch (e) {
          sqlite.exec('ROLLBACK');
          throw e;
        }
      });
      chain = run.catch(() => {});
      return run;
    },
    async init() {
      sqlite.exec(SQLITE_SCHEMA + COMMON_SCHEMA('INTEGER', 'INTEGER'));
    },
    close: async () => sqlite.close(),
    describe: () => `sqlite (${file})`,
  };
}

export const db = backend;
await db.init();
