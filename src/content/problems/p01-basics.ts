/** Compact builder for beginner problems (single approach). */
function basic(o: {
  id: string;
  title: string;
  difficulty?: Difficulty;
  statement: string;
  name: string;
  params: [string, TypeName][];
  returns: TypeName;
  tests: Test[];
  hints: string[];
  idea: string;
  time?: string;
  space?: string;
  py: string;
  java: string;
  compare?: Problem['compare'];
  inplace?: number;
}): Problem {
  const params: Param[] = o.params.map(([name, type]) => ({ name, type }));
  return {
    id: o.id,
    title: o.title,
    difficulty: o.difficulty || 'Easy',
    topic: 'basics',
    statement: o.statement,
    sig: { name: o.name, params, returns: o.returns, inplace: o.inplace },
    tests: o.tests,
    compare: o.compare,
    hints: o.hints,
    approaches: [{ name: 'Direct approach', idea: o.idea, time: o.time || 'O(n)', space: o.space || 'O(1)' }],
    solution: { python: o.py, java: o.java },
  };
}

